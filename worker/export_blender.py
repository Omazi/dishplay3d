"""Run only inside the pinned Blender CLI; exports actual textured OpenMVS geometry."""
import json
from pathlib import Path
import sys

import bpy


def inspect_textured_meshes():
    meshes = [obj for obj in bpy.context.scene.objects if obj.type == "MESH"]
    if not meshes or not any(len(obj.data.polygons) for obj in meshes):
        raise RuntimeError("No mesh faces were imported")
    for obj in meshes:
        if not obj.data.uv_layers:
            raise RuntimeError(f"Mesh lacks UV coordinates: {obj.name}")
        for index in {polygon.material_index for polygon in obj.data.polygons}:
            if index >= len(obj.material_slots):
                raise RuntimeError("Mesh faces have no material")
            material = obj.material_slots[index].material
            if not material or not material.use_nodes:
                raise RuntimeError("Mesh material lacks a texture node graph")
            texture_nodes = [node for node in material.node_tree.nodes if node.type == "TEX_IMAGE" and node.image]
            if not texture_nodes or not any(node.image.size[0] > 0 and node.image.size[1] > 0 for node in texture_nodes):
                raise RuntimeError("Mesh material has no readable image texture")
    return {"mesh_count": len(meshes), "faces": sum(len(obj.data.polygons) for obj in meshes)}


def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    bpy.data.orphans_purge(do_recursive=True)


def main():
    if bpy.app.version != (4, 5, 13):
        raise RuntimeError("Exporter requires Blender 4.5.13; review API changes before updating the pin")
    source, glb, usdz, scale = sys.argv[sys.argv.index("--") + 1:]
    source, glb, usdz = (Path(value).resolve() for value in (source, glb, usdz))
    if not source.is_file() or source.suffix.lower() != ".obj":
        raise RuntimeError("Expected the textured OBJ generated by OpenMVS")
    clear_scene()
    bpy.ops.wm.obj_import(filepath=str(source))
    report = {"source": source.name, "original": inspect_textured_meshes(), "roundtrip_textures_verified": []}
    scale = float(scale)
    bpy.context.scene.unit_settings.system = "METRIC"
    bpy.context.scene.unit_settings.scale_length = 1.0
    # This supplied multiplier is not proof of metric scale. The manifest requires physical review.
    for obj in bpy.context.scene.objects:
        if obj.type == "MESH":
            obj.scale = tuple(value * scale for value in obj.scale)
    bpy.ops.export_scene.gltf(filepath=str(glb), export_format="GLB", export_texcoords=True,
                              export_materials="EXPORT", export_image_format="AUTO", export_yup=True,
                              export_animations=False, export_cameras=False, export_lights=False)
    bpy.ops.wm.usd_export(filepath=str(usdz), export_animation=False, export_uvmaps=True,
                          export_normals=True, export_materials=True, export_textures=True,
                          export_textures_mode="NEW", relative_paths=True,
                          generate_preview_surface=True, convert_orientation=True,
                          export_global_forward_selection="NEGATIVE_Z", export_global_up_selection="Y")
    # Reimport each export, and fail if geometry, UVs or readable image materials disappear.
    clear_scene()
    bpy.ops.import_scene.gltf(filepath=str(glb))
    report["glb"] = inspect_textured_meshes()
    report["roundtrip_textures_verified"].append("glb")
    clear_scene()
    bpy.ops.wm.usd_import(filepath=str(usdz))
    report["usdz"] = inspect_textured_meshes()
    report["roundtrip_textures_verified"].append("usdz")
    (glb.parent / "export-report.json").write_text(json.dumps(report, indent=2) + "\n")


main()
